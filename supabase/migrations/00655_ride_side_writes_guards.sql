-- ── rides: pending scheduled rides per rider ────────────────────────────
-- Runs after rides_normalize_scheduling (triggers fire by name), which sets
-- is_scheduled.
CREATE OR REPLACE FUNCTION public.tg_rides_scheduled_limit()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
DECLARE
  v_count int;
BEGIN
  IF current_user NOT IN ('anon', 'authenticated') OR public.is_admin() OR NOT NEW.is_scheduled THEN
    RETURN NEW;
  END IF;

  SELECT count(*) INTO v_count FROM public.rides
   WHERE customer_id = NEW.customer_id
     AND status = 'searching'
     AND is_scheduled
     AND NOT COALESCE(scheduled_notified, false);
  IF v_count >= 5 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'Puedes tener hasta 5 viajes programados pendientes. Cancela alguno para programar otro.',
      DETAIL = 'scheduled_limit';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.tg_rides_scheduled_limit() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE TRIGGER rides_scheduled_limit
  BEFORE INSERT ON public.rides
  FOR EACH ROW EXECUTE FUNCTION public.tg_rides_scheduled_limit();

-- ── ride_waypoints ───────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.tg_ride_waypoints_client_guard()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
DECLARE
  v_ctx record;
  v_count int;
  v_changed text[];
BEGIN
  IF current_user NOT IN ('anon', 'authenticated') OR public.is_admin() THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  IF auth.uid() IS NOT NULL THEN
    SELECT * INTO v_ctx FROM public._ride_context_for_caller(
      CASE WHEN TG_OP = 'INSERT' THEN NEW.ride_id ELSE OLD.ride_id END);
  END IF;
  IF auth.uid() IS NULL OR NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'Esta parada no es de uno de tus viajes.',
      DETAIL = 'waypoint_not_your_ride';
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF v_ctx.caller_role <> 'customer' THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001',
        MESSAGE = 'Solo el pasajero puede agregar paradas.',
        DETAIL = 'waypoint_not_your_ride';
    END IF;
    IF v_ctx.ride_status NOT IN ('searching', 'accepted', 'driver_en_route', 'arrived_at_pickup', 'in_progress') THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001',
        MESSAGE = 'Ya no puedes cambiar las paradas de este viaje.',
        DETAIL = 'waypoint_locked';
    END IF;
    SELECT count(*) INTO v_count FROM public.ride_waypoints WHERE ride_id = NEW.ride_id;
    IF v_count >= 3 THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001',
        MESSAGE = 'Un viaje puede tener como máximo 3 paradas.',
        DETAIL = 'waypoint_limit';
    END IF;
    NEW.arrived_at := NULL;
    NEW.departed_at := NULL;
    NEW.created_at := now();
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF v_ctx.caller_role <> 'customer'
       OR v_ctx.ride_status NOT IN ('searching', 'accepted', 'driver_en_route', 'arrived_at_pickup')
       OR OLD.arrived_at IS NOT NULL THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001',
        MESSAGE = 'Ya no puedes quitar esta parada: el viaje ya empezó.',
        DETAIL = 'waypoint_locked';
    END IF;
    RETURN OLD;
  END IF;

  -- UPDATE: which columns changed.
  SELECT coalesce(array_agg(n.key), '{}') INTO v_changed
    FROM jsonb_each(to_jsonb(NEW)) n
   WHERE n.value IS DISTINCT FROM (to_jsonb(OLD) -> n.key);

  IF v_ctx.caller_role = 'driver'
     AND NOT EXISTS (SELECT 1 FROM unnest(v_changed) c WHERE c NOT IN ('arrived_at', 'departed_at'))
     AND NOT (NEW.arrived_at IS DISTINCT FROM OLD.arrived_at AND (OLD.arrived_at IS NOT NULL OR NEW.arrived_at IS NULL))
     AND NOT (NEW.departed_at IS DISTINCT FROM OLD.departed_at AND (OLD.departed_at IS NOT NULL OR NEW.departed_at IS NULL)) THEN
    -- The driver stamps arrival and departure once each, with the server's time.
    IF NEW.arrived_at IS DISTINCT FROM OLD.arrived_at THEN
      NEW.arrived_at := now();
    END IF;
    IF NEW.departed_at IS DISTINCT FROM OLD.departed_at THEN
      NEW.departed_at := now();
    END IF;
    RETURN NEW;
  END IF;

  IF cardinality(v_changed) = 0 THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION USING ERRCODE = 'P0001',
    MESSAGE = 'Una parada ya agregada no se puede cambiar.',
    DETAIL = 'waypoint_column';
END;
$$;

REVOKE ALL ON FUNCTION public.tg_ride_waypoints_client_guard() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE TRIGGER trg_ride_waypoints_client_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.ride_waypoints
  FOR EACH ROW EXECUTE FUNCTION public.tg_ride_waypoints_client_guard();

-- ── reviews ──────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.tg_reviews_client_guard()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
BEGIN
  IF current_user NOT IN ('anon', 'authenticated') OR public.is_admin() THEN
    RETURN NEW;
  END IF;

  NEW.comment := NULLIF(btrim(NEW.comment), '');
  IF char_length(NEW.comment) > 1000 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'El comentario puede tener hasta 1000 caracteres.',
      DETAIL = 'review_comment_length';
  END IF;

  -- Featuring and hiding a review are moderation; the date is the server's.
  NEW.is_featured := false;
  NEW.is_visible := true;
  NEW.created_at := now();
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.tg_reviews_client_guard() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE TRIGGER trg_reviews_client_guard
  BEFORE INSERT ON public.reviews
  FOR EACH ROW EXECUTE FUNCTION public.tg_reviews_client_guard();

-- ── delivery_details ─────────────────────────────────────────────────────
-- Named without the trg_ prefix so it fires before trg_delivery_details_generate_otp
-- (triggers fire by name): the OTP it clears is then generated by the server.
CREATE OR REPLACE FUNCTION public.tg_delivery_details_client_guard()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
DECLARE
  v_ctx record;
  v_mode text;
  v_changed text[];
  v_prefix text;
BEGIN
  IF current_user NOT IN ('anon', 'authenticated') OR public.is_admin() THEN
    RETURN NEW;
  END IF;

  IF auth.uid() IS NOT NULL THEN
    SELECT * INTO v_ctx FROM public._ride_context_for_caller(
      CASE WHEN TG_OP = 'INSERT' THEN NEW.ride_id ELSE OLD.ride_id END);
  END IF;
  IF auth.uid() IS NULL OR NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'Este envío no es de uno de tus viajes.',
      DETAIL = 'delivery_not_your_ride';
  END IF;

  IF TG_OP = 'INSERT' THEN
    SELECT r.ride_mode INTO v_mode FROM public.rides r WHERE r.id = NEW.ride_id;
    IF v_ctx.caller_role <> 'customer' OR v_mode IS DISTINCT FROM 'cargo' THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001',
        MESSAGE = 'Este envío no es de uno de tus viajes.',
        DETAIL = 'delivery_not_your_ride';
    END IF;
    IF v_ctx.ride_status NOT IN ('searching', 'accepted', 'driver_en_route', 'arrived_at_pickup') THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001',
        MESSAGE = 'Ya no puedes cambiar los datos de este envío.',
        DETAIL = 'delivery_locked';
    END IF;
    NEW.delivery_otp := NULL;
    NEW.delivery_otp_validated_at := NULL;
    NEW.delivery_photo_url := NULL;
    NEW.pickup_photo_url := NULL;
    NEW.created_at := now();
    RETURN NEW;
  END IF;

  -- UPDATE: only the driver's two proof photos, and only into the ride's folder
  -- of the delivery-photos bucket (the upload Edge Function writes them itself).
  SELECT coalesce(array_agg(n.key), '{}') INTO v_changed
    FROM jsonb_each(to_jsonb(NEW)) n
   WHERE n.value IS DISTINCT FROM (to_jsonb(OLD) -> n.key);
  IF cardinality(v_changed) = 0 THEN
    RETURN NEW;
  END IF;

  v_prefix := '^https://[a-z0-9-]+\.supabase\.co/storage/v1/object/public/delivery-photos/'
              || OLD.ride_id::text || '/[^/?#]+$';
  IF v_ctx.caller_role <> 'driver'
     OR EXISTS (SELECT 1 FROM unnest(v_changed) c WHERE c NOT IN ('delivery_photo_url', 'pickup_photo_url'))
     OR (NEW.delivery_photo_url IS DISTINCT FROM OLD.delivery_photo_url
         AND (NEW.delivery_photo_url IS NULL OR NEW.delivery_photo_url !~ v_prefix))
     OR (NEW.pickup_photo_url IS DISTINCT FROM OLD.pickup_photo_url
         AND (NEW.pickup_photo_url IS NULL OR NEW.pickup_photo_url !~ v_prefix)) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'No puedes cambiar ese dato del envío.',
      DETAIL = 'delivery_column';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.tg_delivery_details_client_guard() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE TRIGGER delivery_details_client_guard
  BEFORE INSERT OR UPDATE ON public.delivery_details
  FOR EACH ROW EXECUTE FUNCTION public.tg_delivery_details_client_guard();

-- ── recurring_rides ──────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.tg_recurring_rides_client_guard()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
DECLARE
  v_count int;
BEGIN
  IF current_user NOT IN ('anon', 'authenticated') OR public.is_admin() THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' THEN
    SELECT count(*) INTO v_count FROM public.recurring_rides
     WHERE customer_id = NEW.customer_id AND status <> 'deleted';
    IF v_count >= 10 THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001',
        MESSAGE = 'Puedes tener hasta 10 viajes recurrentes.',
        DETAIL = 'recurring_limit';
    END IF;
    NEW.created_at := now();
    NEW.last_triggered_at := NULL;
  ELSE
    NEW.created_at := OLD.created_at;
    NEW.last_triggered_at := OLD.last_triggered_at;
  END IF;

  IF NEW.days_of_week IS NULL OR cardinality(NEW.days_of_week) NOT BETWEEN 1 AND 7
     OR EXISTS (SELECT 1 FROM unnest(NEW.days_of_week) d WHERE d IS NULL OR d NOT BETWEEN 1 AND 7) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'Elige al menos un día de la semana.',
      DETAIL = 'recurring_days';
  END IF;

  -- When the next ride is due is the server's call, from the days and the time.
  NEW.next_occurrence_at := CASE WHEN NEW.status = 'active'
    THEN public.compute_next_occurrence(NEW.days_of_week::smallint[], NEW.time_of_day, 'America/Havana')
    END;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.tg_recurring_rides_client_guard() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE TRIGGER trg_recurring_rides_client_guard
  BEFORE INSERT OR UPDATE ON public.recurring_rides
  FOR EACH ROW EXECUTE FUNCTION public.tg_recurring_rides_client_guard();

-- ── verification ─────────────────────────────────────────────────────────
DO $verify$
DECLARE
  v_missing text;
  v_bad text;
BEGIN
  SELECT string_agg(t.tg, ', ') INTO v_missing
    FROM (VALUES ('rides', 'rides_scheduled_limit'),
                 ('ride_waypoints', 'trg_ride_waypoints_client_guard'),
                 ('reviews', 'trg_reviews_client_guard'),
                 ('delivery_details', 'delivery_details_client_guard'),
                 ('recurring_rides', 'trg_recurring_rides_client_guard')) AS t(tbl, tg)
   WHERE NOT EXISTS (SELECT 1 FROM pg_trigger g
                      WHERE g.tgrelid = ('public.' || t.tbl)::regclass
                        AND g.tgname = t.tg AND g.tgenabled = 'O' AND NOT g.tgisinternal);
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION '00655: triggers missing or disabled: %', v_missing;
  END IF;

  -- The three patched bodies are exactly the rehearsed ones.
  SELECT string_agg(e.fn, ', ') INTO v_bad
    FROM (VALUES ('tg_rides_normalize_scheduling()', '334490def0189fc365079bd31942036c'),
                 ('tg_rides_validate_estimated_fare()', '7640f61352e98a66fb890eb03f1f036c'),
                 ('create_rides_for_recurring()', '5ace384a2e19b75c2f340162d46e957a')) AS e(fn, md5)
   WHERE (SELECT md5(replace(p.prosrc, chr(13), '')) FROM pg_proc p
           WHERE p.oid = ('public.' || e.fn)::regprocedure) IS DISTINCT FROM e.md5;
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION '00655: patched bodies differ from the rehearsal: %', v_bad;
  END IF;
END
$verify$;
