-- ============================================================
-- 00655 — what a client may write around a ride: the fare it declares, stops,
-- reviews, delivery details, recurring rides and pending scheduled rides
--
-- Measured in prod on 2026-10-11 as real accounts, inside rolled-back blocks:
--   * rides.estimated_fare_trc: tg_rides_validate_corporate reads the TRC
--     estimate before the CUP one. An employee who declared
--     estimated_fare_trc = 1 on a 3000 CUP ride passed the company's per-ride
--     cap (2000), its monthly budget (500) and its prepaid balance (100); the
--     snapshot that complete_ride_and_pay charges kept the 3000. 1 TRC = 1 CUP
--     (cupToTrc is the identity), and every ride in prod has them equal or the
--     TRC empty.
--   * rides.estimated_fare_cup = 0 (its default when a client leaves it out)
--     skipped tg_rides_validate_estimated_fare entirely: no fare floor, no
--     ceiling (00631), and no estimate snapshot, so complete_ride_and_pay fell
--     to its legacy path and charged whatever the GPS trail said, uncapped.
--     No ride in prod ever had a fare of 0.
--   * ride_waypoints: the rider may update or delete any stop of their ride in
--     any status. Moving a stop already visited onto the straight route took a
--     ride from 3914 to 3000 CUP mid-trip (the waypoint trigger re-prices it).
--     The driver may rewrite every column of a stop (address, order).
--   * recurring_rides: the apps hide the feature (recurring_rides_enabled is
--     not set), but the table takes direct writes and the cron
--     create-recurring-rides runs every 15 minutes. A client inserted 5 rows and
--     the cron turned them into 5 rides with fare 0, outside the ride rate
--     limit (it only counts JWT inserts) and, being scheduled, outside the
--     one-active-ride rule.
--   * reviews: the reviewer sets is_featured, is_visible and created_at, and a
--     comment of any length.
--   * delivery_details: the customer may insert the OTP, its validation time
--     and both proof photos; the driver may rewrite every column (recipient,
--     package). Only the upload Edge Function (service role) writes the photos.
--   * scheduled rides: nothing limits how many a rider keeps pending; they all
--     dispatch when their time comes.
--
-- The rule, enforced on writes by clients (current_user anon or authenticated)
-- that are not platform admins; SECURITY DEFINER functions, cron and the
-- service role are not touched:
--   * a ride's TRC estimate is its CUP estimate (any insert), and a client's
--     ride carries a price above 0;
--   * stops: the rider adds them, at most 3, until the ride ends its trip
--     (in_progress), and may remove one only before pickup and before the driver
--     reaches it; the driver only stamps arrival and departure (server time);
--   * reviews start featured = false, visible, now(), comment up to 1000;
--   * delivery details are born on the rider's own cargo ride before pickup,
--     with the OTP generated by the server and no validation or photos; the
--     driver may only set a photo URL of the ride's folder in delivery-photos;
--   * recurring rides: at most 10 per rider; the server computes
--     next_occurrence_at and keeps last_triggered_at; days are ISO 1..7. The
--     cron only runs while the feature flag recurring_rides_enabled is true,
--     the same flag the apps read (it still creates rides with fare 0: price
--     them before turning the flag on);
--   * at most 5 pending scheduled rides per rider.
--
-- Errors carry a Spanish MESSAGE and a code in DETAIL. The three live functions
-- are patched in place from their live bodies, and only if each body is the one
-- read from prod on 2026-10-11. Rehearsal: supabase/tests/00655/run.sh.
-- ============================================================

