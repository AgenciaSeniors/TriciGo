-- Prints the live definition of the objects a migration touches, to start a rehearsal scaffold.
-- Read-only. Run it through the Supabase MCP (execute_sql) after replacing the names in the first
-- CTE (schema-qualified: public.rides, public.complete_ride_and_pay).
--
-- One row per object or part: functions and procedures (with md5/length of the body, to compare
-- with prod later), tables (columns with defaults, identity and generated expressions; grants and
-- RLS flags), their constraints, indexes and triggers, views and materialized views (with their
-- options, such as security_invoker), and policies. Aggregates and window functions are listed by
-- name only. It does not print sequences, types, or the functions a trigger or a default calls:
-- add those names to the list.
WITH names(name) AS (VALUES ('public.rides'), ('public.complete_ride_and_pay')),
rels AS (
  SELECT c.oid, c.relkind, c.relacl, c.relrowsecurity, c.relforcerowsecurity, c.reloptions, n.name
  FROM pg_class c JOIN names n ON n.name = c.relnamespace::regnamespace::text || '.' || c.relname
),
fns AS (
  SELECT CASE p.prokind WHEN 'p' THEN 'procedure' WHEN 'a' THEN 'aggregate' WHEN 'w' THEN 'window function' ELSE 'function' END AS kind,
         n.name || '(' || pg_get_function_identity_arguments(p.oid) || ')' AS object,
         md5(p.prosrc) || '/' || length(p.prosrc) AS md5,
         CASE WHEN p.prokind IN ('f', 'p') THEN pg_get_functiondef(p.oid) ELSE '-- not printed: ask for it by hand' END AS definition
  FROM pg_proc p JOIN names n ON n.name = p.pronamespace::regnamespace::text || '.' || p.proname
),
tbls AS (
  SELECT 'table' AS kind, r.name AS object, NULL::text AS md5,
         format('CREATE TABLE %s (%s);', r.name, (
           SELECT string_agg(format('%I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                    CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
                    CASE
                      WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                      WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                      WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                      ELSE coalesce(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), '')
                    END), ', ' ORDER BY a.attnum)
           FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
           WHERE a.attrelid = r.oid AND a.attnum > 0 AND NOT a.attisdropped))
         || E'\n-- grants: ' || coalesce(r.relacl::text, 'default')
         || E'\n-- row level security: ' || r.relrowsecurity || ', forced: ' || r.relforcerowsecurity
  FROM rels r WHERE r.relkind IN ('r', 'p')
),
views AS (
  SELECT CASE r.relkind WHEN 'v' THEN 'view' ELSE 'materialized view' END, r.name, NULL::text,
         format('CREATE %s %s%s AS %s',
                CASE r.relkind WHEN 'v' THEN 'OR REPLACE VIEW' ELSE 'MATERIALIZED VIEW' END, r.name,
                coalesce(' WITH (' || array_to_string(r.reloptions, ', ') || ')', ''),
                pg_get_viewdef(r.oid, true))
         || E'\n-- grants: ' || coalesce(r.relacl::text, 'default')
  FROM rels r WHERE r.relkind IN ('v', 'm')
),
cons AS (
  SELECT 'constraint', r.name || ' ' || k.conname, NULL::text,
         format('ALTER TABLE %s ADD CONSTRAINT %I %s;', r.name, k.conname, pg_get_constraintdef(k.oid))
  FROM pg_constraint k JOIN rels r ON r.oid = k.conrelid
),
idx AS (
  SELECT 'index', r.name || ' ' || i.indexrelid::regclass::text, NULL::text, pg_get_indexdef(i.indexrelid) || ';'
  FROM pg_index i JOIN rels r ON r.oid = i.indrelid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid AND k.conrelid = i.indrelid)
),
trg AS (
  SELECT 'trigger', r.name || ' ' || t.tgname, NULL::text, pg_get_triggerdef(t.oid) || ';'
  FROM pg_trigger t JOIN rels r ON r.oid = t.tgrelid
  WHERE NOT t.tgisinternal
),
pols AS (
  SELECT 'policy', format('%s on %s.%s', p.policyname, p.schemaname, p.tablename), NULL::text,
         format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', p.policyname, p.schemaname, p.tablename,
                p.permissive, p.cmd, array_to_string(p.roles, ', '),
                coalesce(' USING (' || p.qual || ')', ''), coalesce(' WITH CHECK (' || p.with_check || ')', ''))
  FROM pg_policies p JOIN names n ON n.name = p.schemaname || '.' || p.tablename
)
SELECT * FROM fns UNION ALL SELECT * FROM tbls UNION ALL SELECT * FROM views UNION ALL SELECT * FROM cons
UNION ALL SELECT * FROM idx UNION ALL SELECT * FROM trg UNION ALL SELECT * FROM pols
ORDER BY 1, 2;
